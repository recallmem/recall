"""Renders the brand assets from the elephant sprites (needs Pillow):

- public/favicon.svg                                  the 16 x 16 mark on a dark square
- public/email/header.png                             the email header: elephant + the "RECALL" lettering
- src/http/dashboard/logo.ts                          the dashboard's header logo (same SVG as the site's)
- ../../integrations/claude-code/.claude-plugin/icon.png   the plugin icon, 512 x 512

Usage (from packages/server): python3 scripts/site/assets.py
"""

import pathlib
import sys

from PIL import Image

HERE = pathlib.Path(__file__).resolve().parent
SERVER = HERE.parent.parent
sys.path.insert(0, str(HERE))
from sprites import PAL, S, svg  # noqa: E402

BG = (12, 11, 10)  # --bg
GRID = (20, 18, 15)  # the email header's 12 px grid lines


def rgb(hex_color):
    h = hex_color.lstrip("#")
    return tuple(int(h[i : i + 2], 16) for i in (0, 2, 4))


def paint(img, rows, ox, oy, scale):
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch == ".":
                continue
            c = rgb(PAL[ch])
            for dx in range(scale):
                for dy in range(scale):
                    img.putpixel((ox + x * scale + dx, oy + y * scale + dy), c)


def favicon():
    rows = S["mark"]
    rects = "".join(
        f'<rect x="{x}" y="{y}" width="1" height="1" fill="{PAL[ch]}"/>'
        for y, row in enumerate(rows)
        for x, ch in enumerate(row)
        if ch != "."
    )
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" shape-rendering="crispEdges">'
        f'<title>Recall</title><rect width="16" height="16" fill="#0c0b0a"/>{rects}</svg>\n'
    )


def email_header():
    """Redraws the header's left part (grid + elephant) and keeps the lettering on the right."""
    path = SERVER / "public" / "email" / "header.png"
    img = Image.open(path).convert("RGB")
    split = 118  # the lettering starts at x = 130
    for x in range(split):
        for y in range(img.height):
            img.putpixel((x, y), GRID if x % 12 == 0 or y % 12 == 0 else BG)
    rows = S["logo"]
    scale = 2
    ox = (split - len(rows[0]) * scale) // 2 + 4
    oy = (img.height - len(rows) * scale) // 2
    paint(img, rows, ox, oy, scale)
    img.save(path, optimize=True)


def plugin_icon():
    img = Image.new("RGB", (512, 512), BG)
    rows = S["logo"]
    scale = 11
    ox = (512 - len(rows[0]) * scale) // 2
    oy = (512 - len(rows) * scale) // 2
    paint(img, rows, ox, oy, scale)
    path = SERVER.parent.parent / "integrations" / "claude-code" / ".claude-plugin" / "icon.png"
    img.save(path, optimize=True)


def dashboard_logo():
    mark = svg("logo")
    return (
        "// Generated by scripts/site/assets.py from the site's elephant sprite; do not edit.\n"
        'import { html } from "hono/html";\n\n'
        "/** The elephant logo, the same SVG as the public site's header. */\n"
        f"export const LOGO = html`{mark}`;\n"
    )


def main():
    (SERVER / "public" / "favicon.svg").write_text(favicon())
    email_header()
    plugin_icon()
    (SERVER / "src" / "http" / "dashboard" / "logo.ts").write_text(dashboard_logo())
    print("written: favicon.svg, email/header.png, plugin icon.png, dashboard/logo.ts")


if __name__ == "__main__":
    main()
